$ErrorActionPreference = 'Stop'
$root = Split-Path $PSScriptRoot -Parent
$out = Join-Path $PSScriptRoot 'embedded.h'

$items = @(
  @{ name = 'res_index_html'; path = Join-Path $root 'ui\index.html' },
  @{ name = 'res_app_js';     path = Join-Path $root 'ui\app.js' },
  @{ name = 'res_styles_css'; path = Join-Path $root 'ui\styles.css' },
  @{ name = 'res_net_ps1';    path = Join-Path $PSScriptRoot '..\ps\net.ps1' },
  @{ name = 'res_ttlfix_exe'; path = Join-Path $PSScriptRoot 'win\ttlfix.exe' },
  @{ name = 'res_wv2_loader'; path = Join-Path $root 'WebView2Loader.dll' },
  @{ name = 'res_windivert_dll'; path = Join-Path $PSScriptRoot 'win\WinDivert.dll' },
  @{ name = 'res_windivert_sys'; path = Join-Path $PSScriptRoot 'win\WinDivert64.sys' },
  @{ name = 'res_windivert_lic'; path = Join-Path $PSScriptRoot 'win\WinDivert-LICENSE.txt' }
)

$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine('#pragma once')
[void]$sb.AppendLine('/* generated by native\gen-embedded.ps1 - do not edit */')
foreach ($i in $items) {
  if (-not (Test-Path $i.path)) { throw "missing $($i.path)" }
  $bytes = [System.IO.File]::ReadAllBytes($i.path)
  [void]$sb.AppendLine("static const unsigned char $($i.name)[] = {")
  $line = New-Object System.Text.StringBuilder
  for ($n = 0; $n -lt $bytes.Length; $n++) {
    if ($n -gt 0) { [void]$line.Append(',') }
    [void]$line.Append($bytes[$n])
    if (($n % 24) -eq 23) { [void]$sb.AppendLine($line.ToString()); $line.Clear() | Out-Null }
  }
  if ($line.Length -gt 0) { [void]$sb.AppendLine($line.ToString()) }
  [void]$sb.AppendLine('};')
  [void]$sb.AppendLine("static const DWORD $($i.name)_len = $($bytes.Length);")
}
[System.IO.File]::WriteAllText($out, $sb.ToString(), (New-Object System.Text.UTF8Encoding($false)))
Write-Host "embedded.h: $([math]::Round((Get-Item $out).Length / 1KB)) KB"

